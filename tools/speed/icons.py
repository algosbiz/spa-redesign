"""
Draws the Font Awesome icons the site uses as CSS masks (src/styles/icons.css),
so that no icon font is fetched: three files, 14 KB, came down at the highest
priority as a page opened, for a phone and an arrow on the first screen.

    python tools/speed/icons.py        (needs: pip install fonttools brotli)

Run it again after adding a "fa-..." class to a component: it reads the names
from src/ and the outlines from public/webfonts/, the live site's own subsets
(a name they do not have is reported).

Each icon stays the `::before` of its <i>, in the text's colour, with the
glyph's own width, so every rule that sizes, colours, turns or moves an <i>
works as before. The <i> has the line of the icon fonts (1em, its baseline
0.125em from the bottom) without needing their files: its own font counts for
nothing (line-height 0) and the icon's box makes the line.
"""
import re
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = {
    "fa-solid": "fa-solid-900",
    "fa-regular": "fa-regular-400",
    "fa-light": "fa-light-300",
    "fa-brands": "fa-brands-400",
}
UNITS, ASCENT, DESCENT = 512, 448, 64  # the four fonts' own (hhea)

# The character behind each name: the live stylesheet's own list.
live = (ROOT / "src/styles/live.css").read_text(encoding="utf8")
codes = {name: int(code, 16) for name, code in re.findall(r"\.(fa-[\w-]+):where\(\.lh,\.lh \*\):before \{\s*content: \"\\([0-9a-f]+)\"", live)}

# The icons used: a style and a name on one line of a component, or a name
# alone in data for an <i> whose style is in the component (ContactSection).
used = set()
for path in sorted((ROOT / "src").rglob("*.ts*")):
    if "admin" in path.parts:
        continue
    for line in path.read_text(encoding="utf8").splitlines():
        names = [n for n in re.findall(r"\bfa-[\w-]+", line) if n not in FONTS and n not in ("fa-fw", "fa-classic")]
        styles = [s for s in re.findall(r"\bfa-[\w-]+", line) if s in FONTS]
        if not styles and re.search(r"\bicon: \"fa-", line):
            styles = ["fa-light"]
        if len(styles) == 2 and len(names) == 2:  # a ? "fa-brands fa-x" : "fa-regular fa-y"
            used.update(zip(styles, names))
        else:
            used.update((s, n) for s in styles for n in names)


def number(value):
    return f"{value:.4f}".rstrip("0").rstrip(".") or "0"


fonts = {style: TTFont(ROOT / f"public/webfonts/{file}.woff2") for style, file in FONTS.items()}
rules = []
for style, name in sorted(used):
    font = fonts[style]
    glyph = font.getBestCmap().get(codes.get(name, -1))
    if not glyph:
        print(f"no outline: {style} {name}")
        continue
    width = font["hmtx"][glyph][0]
    pen = SVGPathPen(font.getGlyphSet(), ntos=lambda v: number(round(v, 1)))
    font.getGlyphSet()[glyph].draw(TransformPen(pen, (1, 0, 0, -1, 0, ASCENT)))
    svg = f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {width} {UNITS}'><path d='{pen.getCommands()}'/></svg>"
    url = "data:image/svg+xml," + svg.replace("#", "%23").replace("<", "%3c").replace(">", "%3e")
    rules.append(f'.{style}.{name}:where(.lh, .lh *)::before {{\n  --fa: url("{url}");\n  width: {number(width / UNITS)}em;\n}}')


shared = ",\n".join(f".{style}:where(.lh, .lh *)::before" for style in FONTS)
arrows = ",\n".join(f".{button} .icon_box .{icon}:where(.lh, .lh *)" for button in ("btn-one", "btn-two", "btn-two-light") for icon in ("icon_first", "icon_second"))
css = f"""/*
 * The site's icons: Font Awesome outlines as masks, no icon font to fetch.
 * GENERATED by tools/speed/icons.py, do not edit by hand.
 */
{shared.replace("::before", "")} {{
  line-height: 0;
}}
/* The buttons' arrows are inline-flex with a line of 1 in live.css, where an
   empty box has its baseline at its foot: the button came out 2px taller. */
{arrows} {{
  display: inline-block;
  line-height: 0;
}}
{shared} {{
  content: "";
  display: inline-block;
  height: 1em;
  vertical-align: -{number(DESCENT / UNITS)}em;
  background: currentColor;
  -webkit-mask: var(--fa, none) 0 0 / 100% 100% no-repeat;
  mask: var(--fa, none) 0 0 / 100% 100% no-repeat;
}}
""" + "\n".join(rules) + "\n"
(ROOT / "src/styles/icons.css").write_text(css, encoding="utf8", newline="\n")
print(f"{len(rules)} icons, {len(css) / 1024:.1f} KB")
